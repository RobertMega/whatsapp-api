test('playwright affiliate session prefers the saved profile directory over storage state when both are configured', async () => {
  const persistentCalls = []
  let contextClosed = false

  const session = await createPlaywrightAffiliateSession({
    storageStatePath: 'sessions/affiliate-storage-state.json',
    userDataDir: 'sessions/affiliate-profile',
    playwrightModule: {
      chromium: {
        async launch() {
          throw new Error('storage state should not be used first')
        },
        async launchPersistentContext(userDataDir, options) {
          persistentCalls.push({ userDataDir, options })

          return {
            pages() {
              return [{
                setDefaultTimeout() {},
                async goto() {},
                async waitForLoadState() {},
                url() {
                  return 'https://www.mercadolivre.com.br/afiliados/linkbuilder#hub'
                },
                async evaluate() {
                  return {
                    status: 200,
                    body: JSON.stringify({
                      urls: [{ short_url: 'https://meli.la/teste' }],
                    }),
                  }
                },
              }]
            },
            async close() {
              contextClosed = true
            },
            async storageState() {},
          }
        },
      },
    },
  })

  const payload = await session.createLink({
    urls: ['https://www.mercadolivre.com.br/p/produto'],
    tag: 'rm20250209133551',
  })

  assert.equal(persistentCalls.length, 1)
  assert.equal(persistentCalls[0].userDataDir, 'sessions/affiliate-profile')
  assert.deepEqual(persistentCalls[0].options.args, [
    '--no-sandbox',
    '--disable-setuid-sandbox',
    '--disable-dev-shm-usage',
    '--no-first-run',
    '--no-default-browser-check',
  ])
  assert.equal(payload.urls[0].short_url, 'https://meli.la/teste')

  await session.close()
  assert.equal(contextClosed, true)
})

test('affiliate provider retries with the saved profile when the storage state is expired and refreshes it', async () => {
  const calls = []
  const savedStates = []
  let sessionAttempts = 0

  const provider = createAffiliateLinkProvider({
    tag: 'rm20250209133551',
    storageStatePath: 'sessions/affiliate-storage-state.json',
    userDataDir: 'sessions/affiliate-profile',
    createAffiliateSession: async ({ storageStatePath, userDataDir }) => {
      sessionAttempts += 1

      if (sessionAttempts === 1) {
        assert.equal(storageStatePath, 'sessions/affiliate-storage-state.json')

        return {
          async createLink() {
            throw new Error('Mercado Livre affiliate session expired or is not authorized.')
          },
          async close() {},
        }
      }

      assert.equal(userDataDir, 'sessions/affiliate-profile')

      return {
        async createLink(payload) {
          calls.push(payload)

          return {
            urls: [
              {
                short_url: 'https://meli.la/novo-link',
              },
            ],
          }
        },
        async saveStorageState(path) {
          savedStates.push(path)
        },
        async close() {},
      }
    },
  })

  const affiliateLink = await provider.getAffiliateLink({
    id: 'MLB6204289',
    permalink: 'https://www.mercadolivre.com.br/creatina-100-pura-300g-integralmedica/p/MLB6204289',
  })

  assert.deepEqual(affiliateLink, {
    url: 'https://meli.la/novo-link',
    source: 'affiliate',
    usedFallback: false,
  })
  assert.equal(sessionAttempts, 2)
  assert.deepEqual(savedStates, ['sessions/affiliate-storage-state.json'])
  assert.deepEqual(calls, [
    {
      urls: ['https://www.mercadolivre.com.br/creatina-100-pura-300g-integralmedica/p/MLB6204289'],
      tag: 'rm20250209133551',
    },
  ])
})

