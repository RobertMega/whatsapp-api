import test from 'node:test'
import assert from 'node:assert/strict'

import {
  createAffiliateLinkProvider,
  createPlaywrightAffiliateSession,
} from '../../src/bot/providers/affiliate-link-provider.js'

test('affiliate provider returns the short affiliate link generated by the authenticated session', async () => {
  const calls = []
  let closed = false

  const provider = createAffiliateLinkProvider({
    tag: 'rm20250209133551',
    createAffiliateSession: async () => ({
      async createLink(payload) {
        calls.push(payload)

        return {
          urls: [
            {
              short_url: 'https://meli.la/2Bq2Xkp',
              long_url: 'https://www.mercadolivre.com.br/social/test?ref=abc',
            },
          ],
        }
      },
      async close() {
        closed = true
      },
    }),
  })

  const affiliateLink = await provider.getAffiliateLink({
    id: 'MLB6204289',
    permalink: 'https://www.mercadolivre.com.br/creatina-100-pura-300g-integralmedica/p/MLB6204289',
  })

  assert.deepEqual(affiliateLink, {
    url: 'https://meli.la/2Bq2Xkp',
    source: 'affiliate',
    usedFallback: false,
  })
  assert.deepEqual(calls, [
    {
      urls: ['https://www.mercadolivre.com.br/creatina-100-pura-300g-integralmedica/p/MLB6204289'],
      tag: 'rm20250209133551',
    },
  ])

  await provider.close()
  assert.equal(closed, true)
})

